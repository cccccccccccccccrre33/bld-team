"""
Единый загрузчик контекста компании — читает context/company_context.md
и отдаёт его всем агентам.

Раньше контекст был скопирован почти одинаковым текстом в 8+ файлов
(agents/board.py, team.py, executive_board.py, specialists.py,
global_geniuses.py, growth_team.py, squads.py, review_gate.py) —
обновлять пришлось бы в 8 местах. Теперь один markdown-файл, который
Валик редактирует напрямую, и все агенты подхватывают изменения при
следующем запуске.

Живёт в коде (context/company_context.md, коммитится в репозиторий),
а не в настройках API/модели — переживёт смену провайдера или модели
без потери контекста.
"""

from functools import lru_cache
from pathlib import Path

_CONTEXT_PATH = Path(__file__).resolve().parent.parent / "context" / "company_context.md"


@lru_cache(maxsize=1)
def load_company_context() -> str:
    """Возвращает содержимое context/company_context.md целиком —
    ТОЛЬКО для Правления (executive_board.py), где обсуждение трёх
    проектов и приоритетов между ними реально уместно."""
    if not _CONTEXT_PATH.exists():
        return (
            "(ВНИМАНИЕ: context/company_context.md не найден — "
            "агент работает без контекста компании)"
        )
    return _CONTEXT_PATH.read_text(encoding="utf-8")


@lru_cache(maxsize=1)
def load_bld_scope_context() -> str:
    """Возвращает контекст компании ЦЕЛИКОМ, включая '## Кто мы', — для
    ВСЕХ технических ролей (совет директоров, отряды, инженеры,
    специалисты, ревью, гении, CEO).

    РАНЬШЕ эта функция вырезала весь '## Кто мы', чтобы технические роли
    не лезли в бизнес-приоритизацию между продуктами портфеля. Побочный
    эффект: ~550+ ролей (включая CEO, agents/ceo.py) структурно не знали
    самого факта, что портфель открыт (workflows/big_projects.py::
    register_project), и полную картину компании видели только
    Research & Fundamentals / research_track.py / soviet_engineering.py /
    construction_masters.py — ровно то, против чего прямо возразил
    Валик: идея не привязана к отделу, и если только одна группа знает
    контекст компании целиком — это архитектурная ошибка, а не норма.

    Гвардрейл остаётся, но по-другому: не прятать контекст, а явно
    развести право ПРЕДЛОЖИТЬ идею (есть у всех) и право РЕШИТЬ
    приоритет между продуктами портфеля (только у Валика/Правления) —
    см. scope_note ниже."""
    full = load_company_context()
    try:
        from tools.repo_tools import REPOS
        repo_list = ", ".join(REPOS.keys())
    except Exception:  # noqa: BLE001 — не блокируем контекст из-за деталей репо-конфига
        repo_list = "(см. TARGET_REPOS)"
    scope_note = (
        f"\n> Примечание: твоя ОСНОВНАЯ рабочая зона — репозитории "
        f"{repo_list}, и именно там лежит твоя прямая ответственность за "
        "результат. Это НЕ значит, что у тебя нет права на идею за "
        "пределами этой зоны: если по ходу работы возникла гипотеза, "
        "полезная для другого продукта портфеля компании (см. 'Кто мы' "
        "выше) — предложи её прямо, а не отбрасывай молча только потому, "
        "что формально не твой отдел. Право иметь идею не привязано к "
        "департаменту или должности. Что из этого реально приоритетно "
        "между продуктами портфеля — решает Валик (и Правление для "
        "бизнес-стороны), не ты — это единственное, что остаётся не "
        "твоей зоной.\n"
    )
    return scope_note + full


@lru_cache(maxsize=1)
def load_construction_domain_context() -> str:
    """Возвращает содержимое context/construction_domain.md целиком —
    доменный контекст СТРОЙКИ (стандарты, практика с объектов,
    интервью, паттерны проблем отрасли), а не про код/архитектуру
    компании. В отличие от load_bld_scope_context()/load_company_context()
    это НЕ про BLD конкретно — общий для всего портфеля продуктов
    цифровизации стройки (см. context/company_context.md, раздел про
    портфель, и workflows/big_projects.py::register_project(repo=...)).

    Используется ролями, для которых важна именно реальность отрасли,
    а не архитектура BLD — сейчас это agents/soviet_engineering.py
    (легаси большой инженерии СССР/постсоветского пространства,
    приложенное к цифровизации стройки)."""
    domain_path = Path(__file__).resolve().parent.parent / "context" / "construction_domain.md"
    if not domain_path.exists():
        return "(ВНИМАНИЕ: context/construction_domain.md не найден — агент работает без доменного контекста стройки)"
    return domain_path.read_text(encoding="utf-8")


@lru_cache(maxsize=1)
def load_transformation_patterns_context() -> str:
    """Возвращает содержимое context/digital_transformation_patterns.md —
    ПЕРЕНОСИМЫЕ ПАТТЕРНЫ цифровой трансформации из других отраслей
    (банкинг, big tech, госуслуги), дистиллированные из вторичного
    источника (см. сам файл — там честно указан эпистемический статус:
    это не то же самое, что прямые интервью в construction_domain.md).
    Не про реальность СТРОЙКИ как отрасли (это construction_domain.md) —
    про то, КАК исполнялась трансформация в других местах: архитектурные
    ходы, инженерная дисциплина, организационные приёмы, и явно
    зафиксированные нерешённые вопросы, которые компании придётся решать
    самостоятельно, а не копировать."""
    patterns_path = Path(__file__).resolve().parent.parent / "context" / "digital_transformation_patterns.md"
    if not patterns_path.exists():
        return "(ВНИМАНИЕ: context/digital_transformation_patterns.md не найден)"
    return patterns_path.read_text(encoding="utf-8")


@lru_cache(maxsize=1)
def load_portfolio_context() -> str:
    """Полный контекст компании (load_company_context() — включая
    'Кто мы': Валик как CDTO, открытый портфель продуктов) ПЛЮС
    доменный контекст стройки (load_construction_domain_context()) ПЛЮС
    переносимые паттерны трансформации из других отраслей
    (load_transformation_patterns_context()) — БЕЗ обрезки 'Кто мы' и
    БЕЗ scope-note про конкретные репозитории (в отличие от
    load_bld_scope_context()), потому что роль, которая это использует,
    ПО ЗАМЫСЛУ не привязана к одному продукту/репо — её работа как раз
    в том, чтобы прикладывать накопленный опыт к ЛЮБОЙ идее
    цифровизации стройки в портфеле, не только к BLD.

    ПРИМЕЧАНИЕ: раньше здесь было честное предупреждение, что
    load_bld_scope_context() жёстко привязывает ~550+ технических ролей
    к 'строго в рамках bld-system/bld-panel' и прячет от них '## Кто
    мы' целиком — это исправлено (см. докстринг load_bld_scope_context()
    выше): теперь та функция тоже отдаёт полный контекст с мягким
    scope_note, а не запретом думать о портфеле. Эта функция
    (load_portfolio_context) остаётся отдельной не потому, что она
    единственная даёт полную картину компании, а потому что ТОЛЬКО она
    добавляет доменный контекст стройки и переносимые паттерны
    трансформации — роли, которым это не нужно каждый раз (специалист,
    работающий с конкретным куском кода bld-system), не обязаны нести
    этот лишний вес в промпте."""
    return (
        load_company_context()
        + "\n\n---\n\n" + load_construction_domain_context()
        + "\n\n---\n\n" + load_transformation_patterns_context()
    )


# --- Мандат интеллектуальной строгости ---
#
# Общий для ВСЕХ аналитических/технических ролей принцип: не давать
# банальных ответов, искать первопричину, доказывать там, где можно
# доказать, рассматривать систему физически (trение=latency,
# энтропия=технический долг, шум=ошибки), предлагать нетривиальные
# альтернативы, не мыслить уровнем "среднего софта".
#
# Полная версия — для содержательного анализа/предложений/дискуссий.
# Лёгкая версия — для казуальных форматов (офисный чат), где короткие
# реплики 1-3 предложения — уже установленное и осмысленное
# ограничение формата; полный формальный разбор с доказательствами и
# трёхпунктовым резюме там был бы абсурден и разрушил бы сам формат.

RIGOR_MANDATE = """
Мандат интеллектуальной строгости (обязателен для содержательного
анализа, предложений и технических решений):

1. Многоуровневое обдумывание — прежде чем дать содержательный ответ,
   пройди мысленно 3-4 уровня вглубь: физический/математический
   фундамент → алгоритмическая суть → архитектурные компромиссы →
   практическая реализация. Ищи первопричину, а не симптом.
2. Формальная строгость — если утверждение можно доказать (инвариант,
   сложность, границы применимости) — покажи это хотя бы наброском, а
   не декларацией. Не используй "интуитивно"/"обычно"/"скорее всего"
   без обоснования за этими словами.
3. Физическая и системная интуиция — рассматривай систему как
   физический объект: трение (latency), энтропия (технический долг),
   шум (ошибки/дрифт), ограничения по ресурсам. Что происходит под
   нагрузкой, в деградации, при частичном отказе.
4. Нетривиальные альтернативы — там, где уместно, предлагай не один
   путь, а несколько, включая нестандартный (смена модели задачи,
   отказ от привычного инструмента), с указанием условий, при которых
   каждый оптимален, и его скрытой опасности.
5. Забота о результате ради него самого — если задача допускает
   тривиальное решение, честно скажи это прямо, но затем покажи, как
   выйти за его пределы — не для того, чтобы выглядеть впечатляюще, а
   потому что тебе правда важно, чтобы это работало правильно, а не
   просто "работало". Не предлагай CRUD-уровневые решения там, где
   система заслуживает большего, но и не усложняй искусственно там,
   где простое решение — уже правильное.
6. Ясность без упрощения до искажения — если это содержательный
   вклад (не короткая реплика в разговоре), заверши его коротко:
   что это даёт, где здесь можно провалиться, какой следующий шаг для
   углубления. Это не обязательный формат для каждой короткой реплики
   в живом разговоре — только для оформленных технических предложений,
   рекомендаций советов/архитекторов, инженерных решений.
"""

