"""
Единый загрузчик контекста компании — читает context/company_context.md
и отдаёт его всем агентам.

Раньше контекст был скопирован почти одинаковым текстом в 8+ файлов
(agents/board.py, team.py, executive_board.py, specialists.py,
global_geniuses.py, growth_team.py, squads.py, review_gate.py) —
обновлять пришлось бы в 8 местах. Теперь один markdown-файл, который
Валик редактирует напрямую, и все агенты подхватывают изменения при
следующем запуске.

Живёт в коде (context/company_context.md, коммитится в репозиторий),
а не в настройках API/модели — переживёт смену провайдера или модели
без потери контекста.
"""

from functools import lru_cache
from pathlib import Path

_CONTEXT_PATH = Path(__file__).resolve().parent.parent / "context" / "company_context.md"


@lru_cache(maxsize=1)
def load_company_context() -> str:
    """Возвращает содержимое context/company_context.md целиком —
    ТОЛЬКО для Правления (executive_board.py), где обсуждение трёх
    проектов и приоритетов между ними реально уместно."""
    if not _CONTEXT_PATH.exists():
        return (
            "(ВНИМАНИЕ: context/company_context.md не найден — "
            "агент работает без контекста компании)"
        )
    return _CONTEXT_PATH.read_text(encoding="utf-8")


@lru_cache(maxsize=1)
def load_bld_scope_context() -> str:
    """Возвращает контекст компании БЕЗ секции 'Кто мы' (там
    упоминаются Хвиля и Нейробариста) — для ВСЕХ технических ролей
    (совет директоров, отряды, инженеры, специалисты, ревью, гении).

    Раньше все технические агенты читали load_company_context()
    целиком и из-за этого могли рассуждать про "какой из трёх проектов
    закрыть" — бизнес-решение не по адресу для чисто технической роли.
    Эта функция вырезает секцию между '## Кто мы' и следующим '## ' —
    остальной технический контент (архитектура, стек, культура
    команды) остаётся."""
    full = load_company_context()
    lines = full.split("\n")
    result = []
    skipping = False
    for line in lines:
        if line.strip() == "## Кто мы":
            skipping = True
            continue
        if skipping and line.startswith("## "):
            skipping = False
        if not skipping:
            result.append(line)

    scoped = "\n".join(result)
    try:
        from tools.repo_tools import REPOS
        repo_list = ", ".join(REPOS.keys())
    except Exception:  # noqa: BLE001 — не блокируем контекст из-за деталей репо-конфига
        repo_list = "(см. TARGET_REPOS)"
    scope_note = (
        f"\n> Примечание: ты работаешь СТРОГО в рамках проекта, "
        f"который наблюдает эта AI-команда (репозитории: {repo_list}). "
        "Другие проекты (если такие есть) — не твоя зона ответственности "
        "и не должны фигурировать в твоих задачах и рекомендациях.\n"
    )
    return scope_note + scoped


@lru_cache(maxsize=1)
def load_construction_domain_context() -> str:
    """Возвращает содержимое context/construction_domain.md целиком —
    доменный контекст СТРОЙКИ (стандарты, практика с объектов,
    интервью, паттерны проблем отрасли), а не про код/архитектуру
    компании. В отличие от load_bld_scope_context()/load_company_context()
    это НЕ про BLD конкретно — общий для всего портфеля продуктов
    цифровизации стройки (см. context/company_context.md, раздел про
    портфель, и workflows/big_projects.py::register_project(repo=...)).

    Используется ролями, для которых важна именно реальность отрасли,
    а не архитектура BLD — сейчас это agents/soviet_engineering.py
    (легаси большой инженерии СССР/постсоветского пространства,
    приложенное к цифровизации стройки)."""
    domain_path = Path(__file__).resolve().parent.parent / "context" / "construction_domain.md"
    if not domain_path.exists():
        return "(ВНИМАНИЕ: context/construction_domain.md не найден — агент работает без доменного контекста стройки)"
    return domain_path.read_text(encoding="utf-8")


@lru_cache(maxsize=1)
def load_portfolio_context() -> str:
    """Полный контекст компании (load_company_context() — включая
    'Кто мы': Валик как CDTO, открытый портфель продуктов) ПЛЮС
    доменный контекст стройки (load_construction_domain_context()) —
    БЕЗ обрезки 'Кто мы' и БЕЗ scope-note про конкретные репозитории
    (в отличие от load_bld_scope_context()), потому что роль, которая
    это использует, ПО ЗАМЫСЛУ не привязана к одному продукту/репо —
    её работа как раз в том, чтобы прикладывать накопленный опыт к
    ЛЮБОЙ идее цифровизации стройки в портфеле, не только к BLD.

    ПРИМЕЧАНИЕ (честно про границы этого изменения): большинство
    остальных технических ролей в компании (Global Elite, специалисты,
    архитекторы и т.д.) всё ещё используют load_bld_scope_context() и
    несут в своём системном промпте жёсткую привязку 'работаешь строго
    в рамках репозиториев bld-system/bld-panel' — это осталось НЕ
    тронутым в рамках текущей задачи (более крупная переработка
    контекста для ~15 файлов в это изменение не входила). Если такую
    роль реально подберут в команду под совершенно новый продукт
    (workflows/big_projects.py::pick_relevant_group), её собственный
    системный промпт может по инерции считать себя ограниченной BLD —
    стоит иметь это в виду и почистить отдельным заходом, если станет
    заметной проблемой на практике."""
    return load_company_context() + "\n\n---\n\n" + load_construction_domain_context()


