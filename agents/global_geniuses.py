"""
Глобальные гении — архетипы по мировым топ-вузам, дополняющие
отечественную четвёрку (физтех/физмат/техмат/мехмат). Используются
в двух ролях:

1. В общем ростере (agents/roster.py) — участвуют в Лаборатории и
   HR 1-на-1 как обычные "люди компании", read-only доступ к коду
   (как и остальные не-инженеры).
2. В пуле инженеров (agents/engineering.py) — лид-инженер может
   "нанять" конкретного специалиста под задачу, если её профиль
   совпадает с его сильной стороной. В этом режиме им выдаётся
   write_file — они реально пишут код.

Поэтому каждый build_* принимает параметр can_write: если True —
добавляется write_file к инструментам.

Профили (коротко, по сути из разбора мировых вузов):
- MIT — быстрый прототип, "умом и руками", широкий инженерный охват
  от железа до алгоритмов, доводит идею до работающей демки.
- Caltech — предельная теоретическая строгость, цена ошибки —
  как в космических миссиях, не терпит "почти правильно".
- Stanford — прикладной AI/статистика с продуктовым чутьём: не просто
  решает задачу, а находит, какую задачу стоит решать.
- CMU — чистый Computer Science, компиляторы, формальные методы,
  строгость кода на уровне математического доказательства.
- Tsinghua (Yao Class) — элитный CS, распределённые системы,
  computer vision, работает на пределе вычислительной мощи.
- PKU — чистая математика, криптография, алгоритмическая неуязвимость.
- USTC — скорость и производительность, тензорные вычисления,
  спокойно оптимизирует то, что другие считают "и так нормально".
- ETH Zurich — формальная верификация, надёжность в духе "баг = смерть
  человека" — если система должна не падать никогда, это они.
- KAIST — HCI, AI-агенты, смотрит на систему глазами человека, который
  ей физически пользуется (прораб, менеджер), а не глазами инженера.
"""

